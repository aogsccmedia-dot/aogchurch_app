#!/usr/bin/env python3
"""Builds Ask SCC's church knowledge base from the website's own pages (so answers always match the site).
Each page is split into short chunks by heading; written to src/lib/kb.generated.ts. Run by build.py."""
import html, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
PAGES = ROOT / "tools" / "site" / "pages"
OUT = ROOT / "src" / "lib" / "kb.generated.ts"
# page → (title, url)
SOURCES = {
    "index": ("Home", "/"), "about": ("About us", "/about"), "our-story": ("Our story", "/our-story"), "beliefs": ("What we believe", "/beliefs"),
    "visit": ("Visit & contact", "/visit"), "get-involved": ("Get involved", "/get-involved"), "go-ye": ("Go Ye: the gospel and evangelism", "/go-ye"),
    "discipleship": ("Discipleship classes", "/discipleship"), "prayer": ("Prayer", "/prayer"), "help": ("How to use the app", "/help"),
    "membership": ("Membership", "/membership"), "code-of-conduct": ("Code of conduct", "/code-of-conduct"), "app": ("Get the app", "/app"),
    "tools": ("Tools (FreeCreator)", "/tools"), "store": ("Store", "/store"), "complaints": ("Raising a concern", "/complaints"),
}
EXTRA = [ROOT / "tools" / "welcome-pack" / "pack.html"]

def text_of(fragment: str) -> str:
    fragment = re.sub(r"<(script|style|svg|form|nav)\b.*?</\1>", " ", fragment, flags=re.S | re.I)
    fragment = re.sub(r"\{\{[^}]*\}\}", " ", fragment)
    fragment = re.sub(r"<br\s*/?>|</(p|li|h\d|div|blockquote)>", "\n", fragment, flags=re.I)
    t = html.unescape(re.sub(r"<[^>]+>", " ", fragment))
    t = re.sub(r"[ \t\r]+", " ", t)
    return re.sub(r"\n\s*\n+", "\n", t).strip()

def chunks(src: str, title: str, url: str):
    body = re.sub(r"<!--.*?-->", "", src, flags=re.S)
    parts = re.split(r"(?=<h[12][^>]*>)", body)
    for p in parts:
        h = re.search(r"<h[12][^>]*>(.*?)</h[12]>", p, re.S)
        head = text_of(h.group(1)) if h else ""
        t = text_of(p)
        if len(t) < 60: continue
        for i in range(0, len(t), 900):           # keep chunks short for retrieval
            piece = t[i:i + 900].strip()
            if len(piece) > 60: yield {"title": f"{title}{' · ' + head if head and head not in title else ''}", "url": url, "text": piece}

def main():
    out = []
    for name, (title, url) in SOURCES.items():
        f = PAGES / f"{name}.html"
        if f.exists(): out += list(chunks(f.read_text(), title, url))
    for f in EXTRA:
        if f.exists(): out += list(chunks(f.read_text(), "Welcome pack", "/welcome-pack"))
    for i, c in enumerate(out): c["id"] = f"k{i}"
    OUT.write_text("// Generated by tools/site/kb.py from the website pages. Do not edit by hand.\n"
                   f"export const KB: {{ id: string; title: string; url: string; text: string }}[] = {json.dumps(out, ensure_ascii=False, indent=0)};\n")
    print(f"kb: {len(out)} chunks, {sum(len(c['text']) for c in out) // 1000}k chars")

if __name__ == "__main__":
    main()
